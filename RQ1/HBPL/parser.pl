%% constraint_variables_scanner(+Term, -Result, +InData, -OutData)
%
%     Scanner that can be used with process_term/6 to add an input
%     and output constraint variables to each call to a 
%     user-defined predicate, and get both the new constraint
%     variables in OutData. For every Term that is a compound term
%     with a non-predefined functor, Result will be unified with a 
%     new term with the same functor as Term and:
%
%      * Arguments: the ones in the original term plus two new free
%        variables which will store the input and output 
%        constraint stores. They are placed just before the degree.
%
%     For example, given:
%         Term   = 'prog_pred(X, 1, DegreeVar)', this 
%     predicate will return 
%         Result  = 'prog_pred(X, 1, Cin, Cout, DegreeVar)', and
%         OutData = InData ++ [Cin, Cout].
%     If constraints are passed due to a1 or a3, then:
%         Result  = 'prog_pred(X, 1, Cin, Cout, DegIn, DegOut)', and
%         OutData = InData ++ [Cin, Cout].
%
%     If Term is a call to a predefined predicate (for example,
%     'append([1], X, [1, 2])'), Result and OutData will be unified
%     with Term and InData, respectively.
%
%     @see process_term/6
%

constraint_variables_scanner(Term, NewTerm, InCtrVars, OutCtrVars) :-
  nonvar(Term),
  not(number(Term)),
  !,
  Term =.. [Functor|Args],
  (
    % Term represents a variable, so it can be ignored
    utilities:atom_is_variable(Functor),
    !,
    NewTerm = Term,
    OutCtrVars = InCtrVars
    ;
    % Higher order call
    Functor == ho_call,
    Args = [HOList, Compiled, Goal, GoalDegreeVars|TermArgs],
    ( % Negation
      HOList = [eval_negation, Neg], !,
      NewHOList = HOList
    ; % Call
      HOList = [HOPred],
      (HOPred == bpl_call 
      ;
       higher_order_predicate(HOPred, [goal])
      ), !,
      NewHOList = HOList
    ; % bpl_apply/2, maplist/2
      HOList = [HOPred, _List],
      (HOPred == bpl_apply ; HOPred == bpl_maplist), !,
      NewHOList = HOList
    ; % truth_degree/2
      HOList = [HOPred, _Number],
      higher_order_predicate(HOPred, [goal, nongoal]), !,
      NewHOList = HOList
    ; % forall/2
      HOList = [HOPred],
      higher_order_predicate(HOPred, [goal, goal]), !,
      NewHOList = HOList
    ; % catch/3
      HOList = [HOPred, _Catcher],
      higher_order_predicate(HOPred, [goal, nongoal, goal]), !,
      NewHOList = HOList
     ; % findall/3
      HOList = [HOPred, _Template, _Bag],
      higher_order_predicate(HOPred, [nongoal, goal, nongoal]), !,
      NewHOList = HOList
     ; % setof/3, bagof/3
      HOList = [HOPred, Template, Bag, Bindings],
      higher_order_predicate(HOPred, [nongoal, goal, nongoal]), !,
      append(Bindings, OutCtrVars1, NewBindings),
      NewHOList = [HOPred, Template, Bag, NewBindings]
    ),
    !,
    (Compiled == yes
     ->
      add_constraint_variables(Goal, NewGoal, OutCtrVars1),
      ( % Nothing to link nor to append when there are no 
        % constraint variables
        OutCtrVars1 == [],
        !,
        Cin = Cout,
        OutCtrVars = InCtrVars
      ; % Cout for the crisp negation must not be linked
        Neg == (\+),
        !,
        OutCtrVars1 = [Cin|_],
        link_last_variable(InCtrVars, Cin),
        %OutCtrVars = InCtrVars
        append(InCtrVars, [Cin, Cin], OutCtrVars) 
      ; % Links Cin and Cout of HO calls with the first Cin and 
        %the last variable Cout in NewGoal
        OutCtrVars1 = [Cin|_],
        link_last_variable(InCtrVars, Cin),
        link_last_variable(OutCtrVars1, Cout),
        % Updates the dynamic constraint variable list
        append(InCtrVars, OutCtrVars1, OutCtrVars) 
      ),
      NewTerm =.. [ho_call, NewHOList, Compiled, NewGoal, [Cin, Cout], GoalDegreeVars|TermArgs]
     ;
      NewTerm =.. [ho_call, HOList, Compiled, Goal, [Cin, Cout], GoalDegreeVars|TermArgs],
      append(InCtrVars, [Cin, Cout], OutCtrVars)
    )
  ;
    % Hypothetical operator
    Term = '=>'('_$'(HypoRules), Goal),
    flags:get_bpl_flag(hypothetical(true)),
    !,
    % Do not apply this scanner to HypoRules. It will be applied later
    % when translating HypoRules (It should be a better way to do this)
    NewTerm = '=>'('_$'(HypoRules), NewGoal), 
    add_constraint_variables(Goal, NewGoal, OutCtrVars1),
    append(InCtrVars, OutCtrVars1, OutCtrVars)
  ;
    % Predefined predicate (built-in) but conjunction, disjunction...
    flags:get_bpl_flag(disjunction(true)),
    \+ is_body_connective(Term),
    utilities:builtin(Term),
    !,
    NewTerm = '$builtin'((Term, Cin=Cout), [Cin, Cout]),
    append(InCtrVars, [Cin, Cout], OutCtrVars)
  ;
    % Builtin, quoted term, or existential operator
    (utilities:builtin(Term) ;
     utilities:is_quoted(Functor, '\'') ;
     Functor == '^' ;
     Functor == '$builtin', flags:get_bpl_flag(disjunction(true))),
    !,
    NewTerm = Term,
    OutCtrVars = InCtrVars
  ;
    % Defined predicates
    % Adds the constraint variables to the scanned term
    Ctrs = [_Cin, _Cout],
    (flags:get_bpl_flag(degree_accumulator(false)) 
     ->
      append(ArgsWithoutDegreeVar, [NewDegreeVar], Args),
      append(ArgsWithoutDegreeVar, Ctrs, NewArgsWithoutDegreeVar),
      append(NewArgsWithoutDegreeVar, [NewDegreeVar], NewArgs)
     ;
      append(ArgsWithoutDegreeVar, [NewDegreeInVar, NewDegreeOutVar], Args),
      append(ArgsWithoutDegreeVar, Ctrs, NewArgsWithoutDegreeVar),
      append(NewArgsWithoutDegreeVar, [NewDegreeInVar, NewDegreeOutVar], NewArgs)
    ),
    NewTerm =.. [Functor|NewArgs],
    % Updates the constraint variables list
    append(InCtrVars, Ctrs, OutCtrVars)
  ),
  !.

constraint_variables_scanner(Term, Term, InData, InData).
  % Term can be ignored because it's a variable or a number


%% extract_constraint_variables_scanner(+Term, -Term, +InData, -OutData)
%
%     Scanner that can be used with process_term/6 to extract
%     degree variables in OutData from each call to a 
%     user-defined predicate. 
%
%     @see process_term/6
%

extract_constraint_variables_scanner(Term, Term, InCtrVars, OutCtrVars) :-
  nonvar(Term),
  not(number(Term)),
  !,
  Term =.. [Functor|Args],
  (
    % Term represents a variable, so it can be ignored
    utilities:atom_is_variable(Functor),
    !,
    OutCtrVars = InCtrVars
  ;
    % Crisp negation
    Functor == ho_call,
    Args = [[eval_negation, (\+)], yes, Goal, [Cin, Cin]|_],
    !,
    link_ho_goal(Goal, [Cin, Cin]),
    append(InCtrVars, [Cin, Cin], OutCtrVars)
  ;
    % Weak unification
    Functor == weak_unify_a3,
    Args = [_, _, _Lambda, Cin, Cout|_],
    !,
    append(InCtrVars, [Cin, Cout], OutCtrVars)
  ;
    % Higher order call
    Functor == ho_call,
    Args = [_HOList, _Compiled, _Goal, ConstraintsVars, _GoalDegreeVars|_TermArgs],
    !,
      (nonvar(ConstraintsVars)
      -> append(InCtrVars, ConstraintsVars, OutCtrVars)
      ;  OutCtrVars = InCtrVars)
  ;
    % Hypothetical operator
    flags:get_bpl_flag(hypothetical(true)),
    Term = '=>'(_HypoRules, _Goal),
    !,
    OutCtrVars = InCtrVars
  ;
    % Predefined predicate (built-in) without constraints
    flags:get_bpl_flag(disjunction(true)),
    Term = '$builtin'(_Builtin, [Cin, Cout]),
    !,
    append(InCtrVars, [Cin, Cout], OutCtrVars)
  ;
    % Quoted term, or existential operator
    ( utilities:builtin(Term) ;
      utilities:is_quoted(Functor, '\'') ;
      Functor == '^' ),
    !,
    OutCtrVars = InCtrVars
  ;
    % Defined predicates
    % Extract the constraint variables from the scanned term
    Ctrs = [Cin, Cout],
    (flags:get_bpl_flag(degree_accumulator(false)) 
     ->
      append(_, [Cin, Cout, _DegreeVar], Args)
     ;
      append(_, [Cin, Cout, _DegreeVarIn, _DegreeVarOut], Args)
    ),
    % Add the constraint variables to the output data
    append(InCtrVars, Ctrs, OutCtrVars)
  ),
  !.

extract_constraint_variables_scanner(Term, Term, InData, InData).
  % Term can be ignored because it's a variable or a number


%% get_variables_scanner(+Term, -Result, +InData, -OutData)
%
%     Scanner that can be used with process_term/6 to count the
%     occurrences of each variable in a term and save them in OutData as
%     a list containing [Term, Count] parings. This scanner always
%     unifies Result with Term. Note that, in this context, "variable"
%     means "atom starting with an uppercase letter or an underscore
%     character".
%
%     @see process_term/6
%

get_variables_scanner(Term, Term, CurrentVars, NewVars) :-
  atom(Term),
  % Term is an atom; if its first char is uppercase, then it represents
  % a variable (variables starting with an underscore character are ignored)
  !,
  (utilities:atom_is_variable(Term) ->
    % Term represents a variable, so it must be added to
    % the list of current variables
    (member([Term, Count], CurrentVars) ->
      % This variable has already been found before
      delete(CurrentVars, [Term, Count], CurrentVarsWithoutTerm),
      NewCount is Count + 1,
      NewVars = [[Term, NewCount]|CurrentVarsWithoutTerm]
    ;
      % This is the first ocurrence of this variable
      NewVars = [[Term, 1]|CurrentVars]
    )
  ;
    % Term doesn't represent a variable
    NewVars = CurrentVars
  ).

get_variables_scanner(Term, Term, Vars, Vars).
  % Term can be ignored because it isn't an atom


