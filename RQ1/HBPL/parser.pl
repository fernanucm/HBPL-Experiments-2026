%% higher_order_predicate(?Name, ?Arguments)
%
%     Succeeds if Name is the name of a higher-order predicate
%     supported by Bousi-Prolog, and Arguments is a list containing
%     the description of its arguments. Each item of Arguments can be
%     either 'goal', 'nongoal' or 'atom' (just for assert/1 and
%     retract/1).
%     Weak and crisp negation are also supported but are not 
%     included in this list.
%

higher_order_predicate(assert,  [atom]).
higher_order_predicate(retract, [atom]).
higher_order_predicate(call,    [goal]).
higher_order_predicate(once,    [goal]).
higher_order_predicate(ignore,  [goal]).
higher_order_predicate(time,    [goal]).
higher_order_predicate(apply,   [nongoal, nongoal]).
higher_order_predicate(maplist, [nongoal, nongoal]).
higher_order_predicate(forall,  [goal, goal]).
higher_order_predicate(findall, [nongoal, goal, nongoal]).
higher_order_predicate(bagof,   [nongoal, goal, nongoal]).
higher_order_predicate(setof,   [nongoal, goal, nongoal]).
higher_order_predicate(catch,   [goal, nongoal, goal]).
higher_order_predicate(phrase,  [goal, nongoal, nongoal]).
higher_order_predicate(phrase,  [goal, nongoal]).
higher_order_predicate(truth_degree, [goal, nongoal]).


%% is_total_goal(+Goal)
%
%     Succeeds if Goal is total, i.e., it contains no variables
%     at positions in which non-variables are expected.
%

is_total_goal(Goal) :-
  (  var(Goal)
   ; number(Goal)
   ; is_list(Goal) 
   ; atom_is_variable(Goal)),
  !,
  fail.

is_total_goal(Goal) :-
  ( Goal = (Goal1, Goal2)
  ; Goal = (Goal1; Goal2) ),
  !,
  is_total_goal(Goal1),
  is_total_goal(Goal2).

is_total_goal(Goal1 *-> Goal2) :-
  !,
  is_total_goal(Goal1 -> Goal2).

is_total_goal(Goal1 -> Goal2) :-
  !,
  is_total_goal(Goal1),
  is_total_goal(Goal2).

is_total_goal('=>'(Rules, Goal)) :-
  flags:get_bpl_flag(hypothetical(true)),
  !,
  is_total_hypo_rules(Rules),
  is_total_goal(Goal).

is_total_goal(Goal) :-
  compound(Goal),
  Goal =.. [Functor|Arguments],
  (higher_order_predicate(Functor, Pattern)
   ; 
   (Functor == not ; Functor == (\+)), 
   Pattern = [goal]),
  !,
  filter_goal_arguments(Arguments, Pattern, GoalArguments),
  maplist(is_total_goal, GoalArguments).

is_total_goal(_Goal) :-
  !.


%% is_total_rule(+Rule)
%
%     Succeeds if Rule is total, i.e., its body is total and
%     its head is not a variable.
%

is_total_rule(Rule) :-
  atom_is_variable(Rule),
  !,
  fail.

is_total_rule((Head :- _Body)) :-
  atom_is_variable(Head),
  !,
  fail.

is_total_rule((_TotalHead :- Body)) :-
  (is_total_goal(Body)
   -> !
   ;  !, fail).

is_total_rule(_TotalHead).


%% is_total_hypo_rules(+Rules)
%
%     Succeeds if all Rules in a hypothetical assumption
%     are total.
%

is_total_hypo_rules(Rules) :-
  (var(Rules) ; atom_is_variable(Rules)),
  !,
  fail.

is_total_hypo_rules(Rule/\MoreRules) :-
  !,
  is_total_rule(Rule),
  is_total_hypo_rules(MoreRules).

is_total_hypo_rules(Rule) :-
  is_total_rule(Rule).



