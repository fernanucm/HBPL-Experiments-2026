%% bousi_prolog_program(-DirectivesDiffList -ReplacedDirectivesDiffList 
%                       -RulesDiffList -EquationsDiffList)
%
%     DCG rule which parses a full Bousi-Prolog program and saves all
%     directives, rules (including facts) and fuzzy relation equations
%     in Directives, Rules and Equations lists, respectively. This rule
%     manages syntax errors and tries to continue parsing if one of
%     them is found, so it won't fail even if the Bousi-Prolog program
%     has errors.
%

% bousi_prolog_program(Directives, Rules, Equations) -->
%   bousi_prolog_program(Directives, [], Rules, [], Equations, []).


bousi_prolog_program(Dir, Dir, RDir, RDir, Rul, Rul, Equ, Equ) -->
  % Normal end-of-file
  [eof(_, _)].

bousi_prolog_program(Diri, Diro, RDiri, RDiro, Ruli, Rulo, Equi, Equo) -->
  % Bousi-Prolog equation
  bpl_equation(Equi, Equ1, _),
  {
    !
  },
  bousi_prolog_program(Diri, Diro, RDiri, RDiro, Ruli, Rulo, Equ1, Equo).
  
bousi_prolog_program(Diri, Diro, RDiri, RDiro, Ruli, Rulo, Equi, Equo) -->
  % Bousi-Prolog specific directive
  % The directive wn_gen_prox_equations generates new proximity equations as well
  bpl_directive(Diri, Dir1, RDiri, RDir1, Equi, Equ1, _),
  {
    !
  },
  bousi_prolog_program(Dir1, Diro, RDir1, RDiro, Ruli, Rulo, Equ1, Equo).

bousi_prolog_program(Diri, Diro, RDiri, RDiro, Ruli, Rulo, Equi, Equo) -->
  % Special include/1 directive
  include_directive(Diri, Dir1, RDiri, RDir1, Ruli, Rul1, Equi, Equ1, _),
  {
    !
  },
  bousi_prolog_program(Dir1, Diro, RDir1, RDiro, Rul1, Rulo, Equ1, Equo).

bousi_prolog_program(Diri, Diro, RDiri, RDiro, Ruli, Rulo, Equi, Equo) -->
  % Prolog directive
  prolog_directive([Directive], _),
  {
    !,
    Diri = [Directive|Dir1]
  },
  bousi_prolog_program(Dir1, Diro, RDiri, RDiro, Ruli, Rulo, Equi, Equo).

bousi_prolog_program(Diri, Diro, RDiri, RDiro, Ruli, Rulo, Equi, Equo) -->
  % Rule or fact
  rule(Rules, [Line, _]),
  {
    !,
    % Rule weight is the degree of the graded rule: Rule with RuleWeight.
    % If the weight is below the lambda-cut, it was not loaded
    (Rules == []
     ->
      Rul1 = Ruli
    ;
      Rules = [[RuleContent, _RuleWeight, _HeadConstraints, _BodyConstraints, _HeadDegreeVars, _BodyDegreeVars, _HypoData]|_HypoRules],
      check_singleton(RuleContent, Line),
      append(Rules, Rul1, Ruli)
    )
  },
  bousi_prolog_program(Diri, Diro, RDiri, RDiro, Rul1, Rulo, Equi, Equo).

bousi_prolog_program(Diri, Diro, RDiri, RDiro, Ruli, Rulo, Equi, Equo) -->
  % If all of the previous rules fail, there must be a syntax error
  % in source code; this rule will try to find it and go on parsing
  bousi_prolog_program_error(Diri, Diro, RDiri, RDiro, Ruli, Rulo, Equi, Equo).

  
