%% control_predicate_tester(+Term)
%
%     Tester that can be used with process_term/6 to scan a clause or
%     goal. This tester fails only when Term is a compound term with a
%     functor different from ,/2, ;/2, ->/2, *->/2 and =>/2 (this last 
%     one when hypothetical reasoning is enabled).
%
%     @see process_term/6
%

%% is_body_connective(+Term)
%
%     Helper predicate which is true if Term is a body connective 
%     (',', ';', '->' ...)

control_predicate_tester(Term) :-
  compound(Term),
  !,
  is_body_connective(Term).

control_predicate_tester(_Term).
  % Tester always succeeds for non-compound terms


is_body_connective(Term) :-
  functor(Term, Functor, Arity),
  (Functor == ',' ; 
   Functor == ';' ; 
   Functor == '->' ; 
   Functor == '*->' ;
   (Functor == '=>', Arity == 2, flags:get_bpl_flag(hypothetical(true)))
   ).



