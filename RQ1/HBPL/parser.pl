%% parsed_term_variables(+Term, -TermVars)
%
%     Get variables from a parsed term. Each variable in a parsed
%     term is an atom starting with a capital letter or an 
%     underscore. It is only used when hypothetical reasoning is 
%     enabled. Otherwise, it returns an empty list.
%

parsed_term_variables(_Term, []) :-
  flags:get_bpl_flag(hypothetical(false)),
  !.
  
parsed_term_variables(Term, TermVars) :-
  parsed_term_variables_aux(Term, DuplicatedTermVars, []),
  sort(DuplicatedTermVars, TermVars).


parsed_term_variables_aux(Term) -->
  { var(Term) ; number(Term) },
  [],
  !.

parsed_term_variables_aux([]) -->
  [],
  !.

parsed_term_variables_aux([X|Xs]) -->
  parsed_term_variables_aux(X),
  parsed_term_variables_aux(Xs),
  !.

parsed_term_variables_aux(Term) -->
  [Term],
  { \+ compound(Term),
    atom_is_variable(Term),
    ! }.

parsed_term_variables_aux(Term) -->
