%%% add_auto_gen_prox_equations(+Directives, +Rules, -InEquations, -OutEquations)
%%%
%%% If Directives is [:- directive(wn_gen_prox_equations, [Measure, Auto])], then 
%%% return in OutEquations all the equations derived from constants in Rules
%%% Otherwise, return InEquations

add_auto_gen_prox_equations([:- directive(Directive, [Measure, Auto])], Rules, InEquations, OutEquations) :-
  Directive==wn_gen_prox_equations,
  \+ is_list(Auto),
  !,
  wn_gen_prox_equations:wn_auto_gen_prox_equations([:- directive(Directive, [Measure, Auto])], Rules, InEquations, OutEquations).
  
add_auto_gen_prox_equations(_Directives, _Rules, Equations, Equations).


%% bpl_directive(-DirectivesIn, -DirectivesOut, -ReplacedDirectivesIn, -ReplacedDirectivesOut, -EquationsIn, -EquationsOut, -LineColumn)
%
%     DCG rule which parses a Bousi-Prolog specific directive and returns
%     it inside a directive/2 directive (e.g., ':- transitivity(yes).' is
%     translated into ':- directive(transitivity, [yes]).').
%
%     A directive, such as wn_gen_prox_equations, can be replaced by the 
%     proximity equations it generates.
%

bpl_directive(Diri, Diro, RDiri, RDiro, Equi, Equo, [Line, Column]) -->
  [name(':-', [Line, Column])], 
  term(Term, [], _, _), 
  [name('.', _)],
  {
    parse_expression(Term, ResultTerm),
    ResultTerm =.. [Name|Arguments],
    catch((
      % Checks if specified directive is a valid BPL directive
      directives:is_directive_valid(Name, Arguments),
      % Executes the directive
      directives:exec_directive(Name, Arguments, Equi, Equo),
      (directives:replaced_directive(Name) ->
         Diri = Diro,
         RDiri = [:- directive(Name, Arguments)|RDiro]
        ;
         Diri = [:- directive(Name, Arguments)|Diro],
         RDiri = RDiro)
    % (catcher)
    ), directive_error(ErrorMessage), (
      % Directive isn't valid
      add_message(ErrorMessage, Line, Column, error),
      Diri = Diro
    ))
  }.


%% bpl_equation(-EquationIn, -EquationOut, -LineColumn)
%
%     DCG rule which parses a Bousi-Prolog proximity, similarity or fuzzy
%     relation equation "a <op> b = n." (where <op> can be any of the
%     Bousi-Prolog relation operators) and returns it in Equation list as
%     a term with this syntax: "<name>(a, b, n)" (where <name> is the
%     internal name of <op>). <op> and <name> are related using
%     the relation_name/2 predicate of the 'utilities' module.
%

bpl_equation(Equi, Equo, [Line, Column]) -->
  symbol(Sym1, [Line, Column]), [relation(RelOp, _)], symbol(Sym2, _),
  [name('=', _)], number_(Value, [LineValue, ColumnValue]), [name('.', _)],
  {
    ((Value >= 0.0, Value =< 1.0)
     ->
      utilities:relation_name(RelOp, RelName),
      (RelName == sim,
       flags:get_bpl_flag(lambda_cut(LambdaCut)),
       LambdaCut > Value,
       flags:get_bpl_flag(filtering(Filtering)),
       Filtering==true
       ->
        (flags:get_bpl_flag(filtering_warning(true)) ->
           add_message('Equation not loaded: value is below the lambda cut.',
              LineValue, ColumnValue, warning)
          ;
           true
        ),
        Equi = Equo
      ;
       EqAux =.. [RelName, Sym1, Sym2, Value], 
       Equi = [EqAux|Equo]
       )
     ;
      add_message('Equation value is not a number in the range [0.0, 1.0].',
        LineValue, ColumnValue, error),
      Equi = Equo
    )
  }.


%% include_directive(-DirectivesIn, -DirectivesOut, 
%%                   -ReplacedDirectivesIn, -ReplacedDirectivesOut, 
%%                   -EquationsIn, -EquationsOut,
%%                   -RulesIn, -RulesOut, -LineColumn)
%
%     DCG rule which parses the special include/1 directive, reads the
%     included Bousi-Prolog source code file and return all directives,
%     rules and equations found in it.
%

include_directive(Diri, Diro, RDiri, RDiro, Ruli, Rulo, Equi, Equo, [Line, Column]) -->
  [name(':-', [Line, Column])], atom_('include', _),
  [left_parenthesis(_, _)], atom_(QuotedFile, _), [right_parenthesis(_, _)],
  [name('.', _)],
  {
    % Gets the real path of the included file
    utilities:remove_quotes(QuotedFile, File),
    (is_absolute_file_name(File) ->
      TmpRealFile = File
    ;
      % Joins the path of the BPL file that is being parsed and the
      % included filename to get its real path; this is needed if the
      % BPL file isn't in the current working directory, for example
      % if '/home/user/pl/a.bpl' contains ':- include('b.bpl').' and
      % the file is loaded from '/home/user' using 'ld pl/a.bpl', the
      % real path of the included file isn't 'b.bpl', but 'pl/b.bpl'
      bpl_filename(CurrentFile),
      file_directory_name(CurrentFile, CurrentDirectory),
      concat_atom([CurrentDirectory, '/', File], TmpRealFile)
    ),
    (exists_file(TmpRealFile) ->
      RealFile = TmpRealFile
     ;
      atom_concat(TmpRealFile,'.bpl',RealFile)
    ),
    % Checks whether the included file exists
    (exists_file(RealFile) ->
      % Parses recursively the included file
      parse_file_aux(RealFile, Diri, Diro, RDiri, RDiro, Ruli, Rulo, Equi, Equo)
    ;
      % Included file doesn't exist or path is invalid
      swritef(Message, 'Included file does not exist: \'%w\'.', [TmpRealFile]),
      add_message(Message, Line, Column, error),
      Diri = Diro,
      RDiri = RDiro,
      Ruli = Rulo, 
      Equi = Equo
    )
  }.


%% prolog_directive(-Directive, -LineColumn)
%
%     DCG rule which parses a Prolog directive and returns it in
%     Directive list. If the parsed directive declares new operators,
%     this predicate will add them to custom operator list to allow
%     them to be used in following statements.
%

prolog_directive([Directive], [Line, Column]) -->
  [name(':-', [Line, Column])], 
  term(Term, [], _, _), 
  [name('.', _)],
  {
    parse_expression(Term, ResultTerm),
    % Checks if this directive needs a special treatment
    (ResultTerm = op(OpPrio, OpType, OpName) ->
      (atom(OpName) ->
        % Directive declares a single operator
        declare_custom_operator(OpPrio, OpType, [OpName])
      ;
        % Directive declares a list of operators
        declare_custom_operator(OpPrio, OpType, OpName)
      ),
      Directive = (:- ResultTerm)
    ;
    (ResultTerm = dynamic(Pred/Arity) ->
      % Directive declares a dynamic predicate, so its name and
      % arity must be changed from 'pred/2' to 'prefix_pred/3'
      program_prefix(Prefix),
      concat_atom([Prefix, '_', Pred], NewPred),
      translator:expanded_rule_arity(Arity, NewArity),
      Directive = (:- dynamic(NewPred/NewArity))
    ;
    (ResultTerm = discontiguous(Pred/Arity) ->
      % Directive declares a dynamic predicate, so its name and
      % arity must be changed from 'pred/2' to 'prefix_pred/3'
      program_prefix(Prefix),
      concat_atom([Prefix, '_', Pred], NewPred),
      translator:expanded_rule_arity(Arity, NewArity),
      Directive = (:- discontiguous(NewPred/NewArity))
    ;
      % No special treatment needed
      Directive = (:- ResultTerm)
    )))
  }.


%% rule(-Rule, -LineColumn)
%
%     DCG rule which parses a Prolog/Bousi-Prolog clause and converts
%     it into a list with an intermediate format that can be later
%     used by the 'translator' module. The returned list will have the
%     following items:
%
%      * A copy of the original clause in which the rule's head and
%        each call to a user-defined predicate has been modified in
%        order to add a degree variable and the prefix of the program
%        being compiled.
%      * Lists of head and body constraint variables added to 
%        the rule's body.
%      * Lists of head and body degree variables added to 
%        the rule's body.
%      * Hypothetical data.
%
%     For example, if the program being loaded is called "prog.bpl",
%     given the rule "a(X) :- b(X), c, true", the parser will translate
%     this rule into a list with these items:
%
%      * a) prog_a(X, Ci, Co, DG) :-
%             prog_b(X, Ci, C1, D1), 
%             prog_c(C1, Co, D2), 
%             true.
%      * b) [DG]
%      * c) [D1, D2]
%      * d) [Ci, Co]
%      * e) [C1]
%      * f) hypo(RuleVars, CD)
%
%   New hypothetical rules can come from:
%      1- Adding hypo data when transforming the rule.
%      2- Parsing higher-order predicates with term//4.
%

%  term//3 creates a list of elements in the term
%  parse_expression/2 converts this list into a Prolog term
%  translate_rule adds, by means of the scanners:
%     Degree variable(s): one or two variables depending on degree 
%       accumulator optimization.
%     Block constraint variables: two variables if either a2 or a3
%       weak unification algorithms are selected.
%     The hypothetical term if hypothetical reasoning is enabled. 
%       In this case, several rules may be returned for each single
%       translated rule.

rule(Rules, [Line, Column]) -->
  term(RuleTerm, [], NewHypoRules, [Line, Column]),
  [name('.', _)], % End of a rule
  { parse_and_translate_rule(RuleTerm, [Line, Column], RuleRules),
    append(RuleRules, NewHypoRules, Rules) }.


%% parse_and_translate_rule(+RuleTerm, +Location, -Rules)
%     Translates the list of terms and operators returned by term/2
%     into a real Prolog term
%
parse_and_translate_rule(RuleTerm, Location, Rules) :-
  parse_expression(RuleTerm, RulePrologTerm),
  translate_rule(RulePrologTerm, Location, Rules).


%% translate_rule(+RulePrologTerms, +Location, -Rules)
%
%    Translates a parsed rule (a Prolog term) into a list of rules, i.e.,
%    adding the prefix to defined predicates, and adding variables
%    for the approximation degree, constraints and the hypothetical
%    term.
%
%    Rule expansion is delayed up to the translator module
%

translate_rule(RulePrologTerm, Location, Rules) :-
    (RulePrologTerm = with(_Rule, _RuleWeight)
     -> GradedRule = RulePrologTerm
     ;  GradedRule = with(RulePrologTerm, 1.0)),
     init_hypothetical_term(HypoTerm),
     % Translate the parsed rule (variables are still atoms and are
     % converted here to Prolog variables)
    translate_rule(GradedRule, HypoTerm, Location, Rules).


%% translate_rule(+Rule, +RuleWeight, +HypoTerm, +Location, -Rules)
%
%    Translate a parsed rule by adding:
%      - The hidden accumulator (if it is a DCG)
%      - Degree variable(s) (one or two, if degree accumulator 
%        optimization is enabled)
%      - Adding constraint variables (for a2 and a3)
%      - Adding the hypothetical term (if hypothetical reasoning 
%        is enabled)
%
%    The rule is rejected if it is below the lambda-cut
%
%    HypoTerm = hypo(SharedVs, RI, RD, CD)

translate_rule(Rule, HypoTerm, Location, Rules) :-
  translate_rule(Rule, _RuleWeight, HypoTerm, Location, Rules).

translate_rule(Rule, RuleWeight, HypoTerm, [Line, Column], Rules) :-
  (flags:get_bpl_flag(hypothetical(true))
   -> % Linearize SharedVs by creating a fresh list of variables
      % which will be weakly unified in the rule body pairwise
      HypoTerm = hypo(SharedVs, RI, RD, CD),
      length(SharedVs, NbrSharedVs),
      length(NewSharedVs, NbrSharedVs),
      get_ri(RI)
   ;  SharedVs = [],
      NewSharedVs = []),
  rule_weight(Rule, RuleWOWeight, RuleWeight),
  \+ atom_is_variable(RuleWOWeight),
  (
    % A DCG
    RuleWOWeight = (HeadTerm --> BodyWithoutDegreeVars),
    !,
    valid_parsed_head(HeadTerm),
    check_builtin_redefinition(HeadTerm, Line, Column),
    dcg_translation('-->'(HeadTerm, BodyWithoutDegreeVars), ':-'(HeadWithoutDegreeVar, TrBodyWithoutDegreeVars)),
    parsed_term_variables([HeadTerm, BodyWithoutDegreeVars], RuleVars),
    translate_rule_body(TrBodyWithoutDegreeVars, Body, BodyDegreeVars, BodyConstraintBlockVars, hypo(body, RuleVars, CD), NewHypoRules)
  ;
    % A rule
    RuleWOWeight = (HeadTerm :- BodyWithoutDegreeVars),
    !,
    valid_parsed_head(HeadTerm),
    check_builtin_redefinition(HeadTerm, Line, Column),
    HeadWithoutDegreeVar = HeadTerm,
    parsed_term_variables([HeadTerm, BodyWithoutDegreeVars], RuleVars),
    translate_rule_body(BodyWithoutDegreeVars, Body, BodyDegreeVars, BodyConstraintBlockVars, hypo(body, RuleVars, CD), NewHypoRules)
  ;
    % A fact
    % Rule = (HeadTerm :- true),
    RuleWOWeight = HeadTerm,
    valid_parsed_head(HeadTerm),
    HeadWithoutDegreeVar = HeadTerm,
    check_builtin_redefinition(HeadTerm, Line, Column),
    Body = true,
    BodyDegreeVars = [],
    BodyConstraintBlockVars = [],
    NewHypoRules = []
  ),
  !,
  % Checks that rule weight is over lambda-cut
  flags:get_bpl_flag(lambda_cut(LambdaCut)),
  flags:get_bpl_flag(filtering(Filtering)),
  (Filtering == true,
   RuleWeight < LambdaCut,
    % Do not add the rule
    (
     flags:get_bpl_flag(filtering_warning(true)) ->
       add_message('Rule not loaded: rule weight is below the lambda cut.',
          Line, Column, warning)
      ;
       true),
     Rules = []
  ;
    % Add the rule
    % Adds a degree variable to rule's head
    add_degree_variables(HeadWithoutDegreeVar, HeadWithDegreeVar, HeadDegreeVars),
    % Adds the constraint variables to rule's head
    add_constraint_variables(HeadWithDegreeVar, HeadWithConstraintsAndDegreeVar, HeadConstraintBlockVars),
    % Adds the initial hypothetical term to rule's head
    add_hypothetical_term(HeadWithConstraintsAndDegreeVar, Head, hypo(head, HypoTerm), _EmptyList),
    % Builds a list with the parsed rule, rule weight, head constraint
    % body constraints, head degree, body degree, and hypothetical data
    % created while scanning its body
    Rules = [[(Head :- Body), RuleWeight, HeadConstraintBlockVars, BodyConstraintBlockVars, HeadDegreeVars, BodyDegreeVars, hypo(SharedVs, NewSharedVs, RI, RD, CD)]|NewHypoRules]
  ).

%% translate_rule_body(+BodyWithoutDegreeVars, -Body, -BodyDegreeVars, -BodyConstraintBlockVars, +HypoData, -NewHypoRules)
%
%    Adds degree variables, constraints, and hypo term to the body
%     HypoData = hypo(body, RuleVars, CD)
%

translate_rule_body(Body, NewBody, BodyDegreeVars, BodyConstraintBlockVars, HypoData, NewHypoRules) :-
  % Replace variable calls
  replace_variable_calls(Body, BodyWithoutDegreeVars), 
  % Registers whter Body contains a disjunction. If not, apply a simplified translation
  %   in add_degree_variables/3 and add_constraint_variables/3
  register_disjunction_in_term(Body),
  % Adds the degree variables to rule's body
  add_degree_variables(BodyWithoutDegreeVars, BodyWithDegreeVars, BodyDegreeVars),
  % Adds the constraint variables to rule's body
  add_constraint_variables(BodyWithDegreeVars, BodyWithCtrsAndDegreeVars, BodyConstraintBlockVars),
  % Adds the hypothetical term to rule's body
  add_hypothetical_term(BodyWithCtrsAndDegreeVars, NewBody, HypoData, NewHypoRules).

%% check_builtin_redefinition(+HeadWithoutDegreeVar, +Line, +Column) 
%
%     Check whether a given predicate is already a built-in. If so, raise an error
%
check_builtin_redefinition(HeadWithoutDegreeVar, Line, Column) :-
  % Checks if the rule's head references an existing predicate
  (utilities:builtin(HeadWithoutDegreeVar) ->
