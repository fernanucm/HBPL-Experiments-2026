%% query(-Query, -NewHypoRules)
%
%     DCG rule which parses and returns a Prolog/Bousi-Prolog query,
%     which must be a term optionally ending with a period in which the
%     main operator isn't ':-'.
%
%     If the query contains assumptions, they are returned in 
%     NewHypoRules.
%

query(Query, NewHypoRules) -->
  %term(Term, [not_allowed_ops([':-'])], NewHypoRules1, _),
  term(Term, [], NewHypoRules1, _),
  query_end,
  {
    parse_expression(Term, ResultTermWithoutCtrsAndDegreeVars),
    build_query(ResultTermWithoutCtrsAndDegreeVars, Query, NewHypoRules2),
    append(NewHypoRules1, NewHypoRules2, NewHypoRules)
  }.


%% build_query(+TermWithoutCtrsAndDegreeVars, -Query, -NewHypoRules)
%
%     Adds to a term the degree variable, and also,
%     for algorithms a2 and a3, input and output 
%     constraint variables.
%
%     If the query contains assumptions, they are returned in 
%     NewHypoRules.
%

build_query(TermWithoutCtrsAndDegreeVars, Query, NewHypoRules) :-
  build_goal(TermWithoutCtrsAndDegreeVars, Query, NewHypoRules),
  Query = [_ResultTerm, BodyConstraintBlockVars, _BodyDegreeVars],
  init_ctr_store(BodyConstraintBlockVars),
  % No need to initialize DegreeVars (a variable is accepted as a degree)
  !.

    
%% build_goal(+TermWithoutCtrsAndDegreeVars, -Query, -NewHypoRules)
%
%     Helper predicate for build_query/4.
%

% WARNING: Revise hypo(query, [], [])
build_goal(TermWithoutCtrsAndDegreeVars, Goal, NewHypoRules) :-
  parsed_term_variables(TermWithoutCtrsAndDegreeVars, _RuleVars),
  translate_rule_body(TermWithoutCtrsAndDegreeVars, ResultTerm, BodyDegreeVars, BodyConstraintBlockVars, hypo(query, [], []), NewHypoRules),
  Goal = [ResultTerm, BodyConstraintBlockVars, BodyDegreeVars],
  !.


%% init_ctr_store(?Constraints)
%
%     Initializes the input constraint store for algorithms 'a2' and 'a3'.
%     It does nothing for others.
%

init_ctr_store([Cin|_]) :-
  flags:get_bpl_flag(weak_unification('a3')),
  !,
  empty_assoc(Cin).
  
init_ctr_store([Cin|_]) :-
  flags:get_bpl_flag(weak_unification('a2')),
  !,
  Cin=[].
  
init_ctr_store(_Cin).


