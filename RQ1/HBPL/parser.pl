%% hypothetical_term_scanner(+Term, -Result, +[HypoData, InRules], -[HypoData, OutRules])
%
%     Scanner that can be used with process_term/6 to add 
%     hypothetical control data to each call to a 
%     user-defined predicate, and get both the new constraint
%     variables in OutData. For every Term that is a compound term
%     with a non-predefined functor, Result will be unified with a 
%     new term with the same functor as Term and:
%
%      * Arguments: the ones in the original term plus .
%
%     HypoData = hypo(head, HypoTerm)
%              | hypo(body, RuleVars, CD)
%              | hypo(query, SharedVars, CD)
%
%     For example, given:
%         Term   = 'prog_pred(X, 1, DegreeVar)',
%         InData = hypo(SharedVs, RI, RD, CD)
%     this predicate will return 
%         Result  = 'prog_pred(X, 1, Cin, Cout, DegreeVar)', and
%         OutData = InData ++ [Cin, Cout].
%     If constraints are passed due to a2 or a3, then:
%         Result  = 'prog_pred(X, 1, Cin, Cout, DegIn, DegOut)', and
%         OutData = InData ++ [Cin, Cout].
%
%     If Term is a call to a predefined predicate (for example,
%     'append([1], X, [1, 2])'), Result and OutData will be unified
%     with Term and InData, respectively.
%
%     @see process_term/6
%

hypothetical_term_scanner(Term, NewTerm, [HypoData, InRules], [HypoData, OutRules]) :-
  nonvar(Term),
  not(number(Term)),
  !,
  Term =.. [Functor|Args],
  (
    % A variable, so it can be ignored
    utilities:atom_is_variable(Functor),
    !,
    NewTerm = Term,
    OutRules = InRules
  ;
    % Higher order predicate with run-time compilation
    Functor == ho_call,
    Args = [[HOPredicate, _]|_],
    ( HOPredicate == bpl_apply
    ; HOPredicate == bpl_maplist),
    !,
    NewTerm = Term,
    OutRules = InRules
  ;
    % Higher order predicate
    Functor == ho_call,
    !,
    (Args = [_, yes|_] % Add hypothetical term only if Term is already compiled by add_degree_variables
     -> ho_hypothetical_term_scanner(Args, NewTerm, [HypoData, InRules], [HypoData, OutRules]) % WARNING: add_hypothetical_term?
     ;  NewTerm = Term,
        OutRules = InRules )
  ;
    % Call to a predefined predicate or a quoted term,
    % so it can be ignored
    (utilities:builtin(Term) ; 
     utilities:is_quoted(Functor, '\'') ;
     Functor == '^'),
    !,
    NewTerm = Term,
    OutRules = InRules
  ;
    % Embedded implication
    % Term = '=>'('_$'(Rules), Goal),
    Term = '=>'(Left, Goal),
    !,
    (Left = '_$'(Rules) ; Left = Rules), % This is because the constraint variables scanner might not been applied
    !,
    (HypoData = hypo(body, RuleVars, CD)
     ;
     HypoData = hypo(query, _SharedVars, CD),
     RuleVars = []),
    NewTerm = '=>'(IdsVs, NewGoal, DI, CD),
    NewCD = [DI|CD],
    translate_hypo_rules(Rules, RuleVars, IdsVs, NewCD, NewRules1),
    ConclusionHypoData = hypo(body, _Free, NewCD),
    add_hypothetical_term(Goal, NewGoal, ConclusionHypoData, NewRules2),
    append([InRules, NewRules1, NewRules2], OutRules)
  ;
    % Call to defined predicate or rule head
    % Adds the hypothetical term to the scanned term
    % HypoData = hypo(head, CD) 
    %          | hypo(body, RuleVars, CD)
    atom_to_hypothetical_atom(Term, NewTerm, HypoData),
    OutRules = InRules
  ).

hypothetical_term_scanner(Term, Term, [HypoData, InRules], [HypoData, InRules]).
  % Term can be ignored because it's a variable or a number


%% ho_hypothetical_term_scanner(+Args, -NewTerm, [+HypoData, +InRules], [-HypoData, -OutRules])
%
%     Scanner that can be used with process_term/6 to add
%     hypothetical control data to each higher-order call to a
%     user-defined predicate.

ho_hypothetical_term_scanner([HOList|Args], NewTerm, [HypoData, InRules], [HypoData, OutRules]) :-
  % Negation, with the form eval_negation(Negation, Goal), Negation \in {\+, not}
  ( HOList = [Functor],
    ( Functor == 'bpl_call'
    ; higher_order_predicate(Functor, [goal])       % once/1...
    ; higher_order_predicate(Functor, [goal, goal]) % forall/2 
    ; higher_order_predicate(Functor, [goal, nongoal, goal]) % catch/3 
    ),
    NewHOList = HOList
  ; HOList = [Functor, _NonGoal],
    ( Functor == 'eval_negation'
    ; higher_order_predicate(Functor, [goal, nongoal]) 
    ),
    NewHOList = HOList
  ; HOList = [Functor, _Template, _Bag],            % findall/3
    higher_order_predicate(Functor, [nongoal, goal, nongoal]),
    NewHOList = HOList
  ; HOList = [Functor, Template, Bag, Bindings],    % bagof/3, setof/3
    higher_order_predicate(Functor, [nongoal, goal, nongoal])
  ),
  !,
  Args = [Compiled, Goal|CtrDegreeVars],
  add_hypothetical_term(Goal, NewGoal, HypoData, NewHypoRules),
  ((Functor == bagof ; Functor == setof)
   -> term_variables(Goal, GoalVars),
      term_variables(NewGoal, NewGoalVars),
      utilities:var_subtract(NewGoalVars, GoalVars, HypoBindings),
      append(HypoBindings, Bindings, NewBindings),
      NewHOList = [Functor, Template, Bag, NewBindings]
   ;  NewHOList = HOList ),
  append(InRules, NewHypoRules, OutRules),
  NewTerm =.. [ho_call, NewHOList, Compiled, NewGoal|CtrDegreeVars].


%% translate_hypo_rules(+Rules, +AllVariables, +Pairs RuleId-SharedVs, +Current_Database_Context, -TranslatedRules) 
%
%     Translates the conjunction of hypothetical rules in the antecedent
%     of an embedded implication.
%
%     Each rule is translated as any normal rule, but including in the
%     hypothetical data the shared variables (SharedVs) with the rule R
%     in which it occurs, the rule context of R (CD), and a new rule 
%     context (_CD) for the translated rules:
%
%       hypo(SharedVs, RI, CD, _CD)
%

translate_hypo_rules((Rule/\Rules), Vs, [IdVs|IdsVs], CD, [NewRule|NewRules]) :-
  !,
  translate_hypo_rules(Rule, Vs, [IdVs], CD, [NewRule]),
  translate_hypo_rules(Rules, Vs, IdsVs, CD, NewRules).

translate_hypo_rules(Rule, AllVs, [RI-SharedVs], CD, NewRules) :-
  parsed_term_variables(Rule, RuleVs),
  intersect_eq(AllVs, RuleVs, SharedVs),
  translate_rule(Rule, _RuleWeight, hypo(SharedVs, RI, CD, _CD), [0,0], NewRules). %WARNING: Should pass Line and Column data instead of [0,0].


%% init_hypothetical_term(-HypoTerm)
%
%     Prepares a hypothetical term for the user program rule being 
%     parsed.
%
%     HypoTerm is of the form hypo(SharedVs, RI, RD, CD), where:
%
%       SharedVs gets []
%       RD gets the user program database context ([])
%       RI gets its value when translating the rule
%

init_hypothetical_term(hypo([], _RI, [], _CD)) :-
  flags:get_bpl_flag(hypothetical(true)),
  !.

init_hypothetical_term(_).


%% atom_to_hypothetical_atom(+Atom, -Result, ?HypoData)
%
%     Adds the hypothetical term hypo(SharedVars, RI, RD, CD) to 
%     either the head, or predicate call at the body, or
%     rule in an antecedent of an embedded implication, where
%
% HypoData = hypo(head, HypoTerm)
%          | hypo(body, RuleVars, CD)
%          | hypo(query, SharedVars, CD)
%
%     For a head, the hypothetical term is given, 
%     For a call, it is constructed from the given CD

%% add_hypothetical_term_to_atom(+Atom, -Result, ?HypotheticalTerm)
%
%     Helper predicate that adds the hypothetical term to Atom

atom_to_hypothetical_atom(Atom, Result, hypo(head, HypotheticalTerm)) :-
  !,
  add_hypothetical_term_to_atom(Atom, Result, HypotheticalTerm).
  
atom_to_hypothetical_atom(Atom, Result, hypo(body, _RuleVars, CD)) :-
  !,
  HypotheticalTerm = hypo(_Free, _RI, _RD, CD),
  add_hypothetical_term_to_atom(Atom, Result, HypotheticalTerm).

atom_to_hypothetical_atom(Atom, Result, hypo(query, SharedVars, CD)) :-
  !,
  HypotheticalTerm = hypo(SharedVars, _RI, _RD, CD),
  add_hypothetical_term_to_atom(Atom, Result, HypotheticalTerm).


add_hypothetical_term_to_atom(Atom, Result, HypotheticalTerm) :-
  Atom =.. [Functor|Vars],
  length(Vars, ExpandedArityMinus1),
  ExpandedArity is ExpandedArityMinus1 + 1,
  translator:actual_rule_arity(ExpandedArity, ActualRuleArity),
  CtrsDegreesVarsNumber is ExpandedArityMinus1 - ActualRuleArity,
  length(CtrsDegreesVars, CtrsDegreesVarsNumber),
  append(HeadVs, CtrsDegreesVars, Vars),
  append(HeadVs, [HypotheticalTerm|CtrsDegreesVars], NewVars),
  Result =.. [Functor|NewVars].



