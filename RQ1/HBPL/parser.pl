%% add_degree_variables(+Term, -Result, -DegreeVars)
%
%     Scans Term, adds a degree variable to all the calls to
%     non-predefined predicates and returns the resulting term in
%     Result. DegreeVars will be unified with a list containing the
%     degree variables appended by this predicate. See
%     degree_variable_scanner/4 for an example.
%
%     @see degree_variable_scanner/4
%

%% add_degree_variables(+Term, -Result, -DegreeVars)
%
%     Helper predicate for add_degree_variables/3.
%

% Weak unification algorithm 'a1'
add_degree_variables(Term, Result, DegreeVars) :-
  flags:get_bpl_flag(degree_accumulator(false)),
  !,
  add_degree_variables_aux(Term, Result, DegreeVars).

% Weak unification algorithm 'a2' or 'a3'
% Optimized version: With degree accumulator
add_degree_variables(Term, Result, DegreeVars) :-
  flags:get_bpl_flag(disjunction(true)),
  !,
  % Add degree variables to Term
  add_degree_variables_aux(Term, NewResult, DegreeVars),
  % Extract each disjunct in NewResult
  disjunctive_normal_form(NewResult, DisjTerm),
  utilities:disjunction_to_list(DisjTerm, Disjuncts),
  % Extract the degree variables in each disjunct
  maplist(extract_degree_variables, Disjuncts, RestDegreeVars),
  % Chain the degree variables of each disjunct
  maplist(link_accumulator_variables, RestDegreeVars),
  utilities:cond_filter_element(utilities:var_or_empty_list, [DegreeVars|RestDegreeVars], NonEmptyDegreeVarsList),
  % Link heads and last element of the degree variables lists
  % For example: [[X1, X2, X3], [Y1, Y2]] -> X1 = Y1, X3 = Y2
  link_heads_and_lasts(NonEmptyDegreeVarsList),
  % Recover the original form of built-in predicates, along 
  % with the call Din = Dout
  replace_builtin(NewResult, Result).

% Weak unification algorithm 'a2' or 'a3'
% Non-optimized version: Without degree accumulator
add_degree_variables(Term, Result, DegreeVars) :-
  % Add degree variables to Term
  add_degree_variables_aux(Term, Result, DegreeVars),
  link_accumulator_variables(DegreeVars).


add_degree_variables_aux(Term, Result, DegreeVars) :-
  utilities:process_term(Term, Result, 
                         [parser:degree_variable_scanner],
                         [parser:control_predicate_tester],
                         [], DegreeVars).


