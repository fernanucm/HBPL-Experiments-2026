%% degree_variable_scanner(+Term, -Result, +InData, -OutData)
%
%     Scanner that can be used with process_term/6 to add degree
%     variables to each call to a user-defined or higher-order
%     predicate and get the new degree variables in OutData. For
%     every Term that is a compound term with a non-predefined
%     functor, Result will be unified with a new term with the
%     following components:
%
%      * Functor: concatenation of the prefix stored in
%        program_prefix/1, an underscore character '_' and the
%        original functor.
%      * Arguments: the ones in the original term plus
%        - A new free variable which will store the approximation
%          degree (degree accumulator optimization disabled).
%        - Two new free variables for input and output degrees
%          (degree accumulator optimization enabled).
%
%     For example, given Term = 'pred(X, 1)', this predicate will
%     return Result = 'prog_pred(X, 1, DegreeVar)' (if degree
%     accumulator optimization is disabled and program_prefix/1
%     contains 'prog') and OutData = [DegreeVar|InData].
%
%     If Term is a call to one of the supported predefined higher-
%     order predicates (for example, apply(pred, List)), Term is
%     encapsulated in the Result term ho_call, where its arguments
%     include the call, arguments, goal degree arguments and output
%     degree.
%
%     If Term is a call to a predefined predicate (for example,
%     'append([1], X, [1, 2])'), and degree accumulator optimization
%     is disabled, Result and OutData will be unified with Term and
%     InData, respectively. 
%     When degree accumulator optimization is
%     enabled, Result is the term '$builtin'((Term, Din = Dout),
%     [Din, Dout]), where Din and Dout are the input and output degree
%     variables, respectively, which will be unified at run-time by
%     Din = Dout. These degree variables must be made explicit for a
%     correct chaining of the degree variables in the body of the
%     program when disjunctions are present. A term is known to
%     include disjunctions if the BPL flag disjunction has been set to
%     true (while not declarative, this trick simplifies the current
%     implementation).
%
%     @see process_term/6
%

degree_variable_scanner(Term, NewTerm, InDegreeVars, OutDegreeVars) :-
  nonvar(Term),
  not(number(Term)),
  !,
  Term =.. [Functor|Args],
  (
    % Term represents a variable, so it can be ignored
    utilities:atom_is_variable(Functor),
    !,
    NewTerm = Term,
    OutDegreeVars = InDegreeVars
  ; % apply/2, maplist/2
    ( Functor == bpl_apply
    ; Functor == bpl_maplist
    ),
    % Args = [PartialGoal, _],
    % !,
    % ho_prepare_degree_variables([Functor|Args], no, PartialGoal, _GoalDegreeVars, NewTerm, InDegreeVars, OutDegreeVars)
    Args = [PartialGoal|MoreArgs],
    !,
    ho_prepare_degree_variables([Functor|MoreArgs], no, PartialGoal, _GoalDegreeVars, NewTerm, InDegreeVars, OutDegreeVars)
  ; % Higher order call with one goal
    ( % Negation
      Term = eval_negation(Neg, Goal),
      !,
      HOList = [eval_negation, Neg]
     ; % Call
      (Term = bpl_call(Goal) 
      ; 
       higher_order_predicate(Functor, [goal]),
       Args = [Goal]),
      !,
      HOList = [Functor] 
     ; % truth_degree
      higher_order_predicate(Functor, [goal, nongoal]),
      Args = [Goal, Number],
      !,
      HOList = [Functor, Number]
     ; % findall/3
      Functor == findall,
      Args = [Template, Goal, Bag],
      !,
      HOList = [Functor, Template, Bag]
     ; % setof/3, bagof/3
      higher_order_predicate(Functor, [nongoal, goal, nongoal]),
      Args = [Template, QuantifiedGoal, Bag],
      !,
      unbind_term(QuantifiedGoal, Goal, Bindings),
      HOList = [Functor, Template, Bag, Bindings]
    ),
    !,
    add_degree_variables_if_total_goal(Goal, NewGoal, Compiled, GoalDegreeVars),
    ho_prepare_degree_variables(HOList, Compiled, NewGoal, GoalDegreeVars, NewTerm, InDegreeVars, OutDegreeVars)
  ; % Higher order call with two goals
    ( % forall/2
      higher_order_predicate(Functor, [goal, goal]),
      Args = [Goal1, Goal2],
      !,
      Goals = (Goal1, Goal2),
      HOList = [Functor]
    ),
    !,
    add_degree_variables_if_total_goal(Goals, NewGoals, Compiled, GoalDegreeVars),
    ho_prepare_degree_variables(HOList, Compiled, NewGoals, GoalDegreeVars, NewTerm, InDegreeVars, OutDegreeVars)
  ; % Higher order call with three goals
    ( % catch/3
      higher_order_predicate(Functor, [goal, nongoal, goal]),
      Args = [Goal1, Catcher, Goal2],
      !,
      Goals = (Goal1 ; Goal2),
      HOList = [Functor, Catcher]
    ),
    !,
    add_degree_variables_if_total_goal(Goals, NewGoals, Compiled, GoalDegreeVars),
    ho_prepare_degree_variables(HOList, Compiled, NewGoals, GoalDegreeVars, NewTerm, InDegreeVars, OutDegreeVars)
  ;
    % Hypothetical operator
    Term = '=>'(HypoRules, Goal),
    flags:get_bpl_flag(hypothetical(true)),
    !,
    NewTerm = '=>'('_$'(HypoRules), NewGoal), % Do not apply this scanner to HypoRules. It will be applied later when translating HypoRules (It should be a better way to do this)
    add_degree_variables(Goal, NewGoal, GoalDegreeVars),
    append(InDegreeVars, GoalDegreeVars, OutDegreeVars)
  ;
    % Predefined predicate (built-in) but conjunction, disjunction...
    flags:get_bpl_flag(degree_accumulator(true)),
    flags:get_bpl_flag(disjunction(true)),
    \+ is_body_connective(Term),
    utilities:builtin(Term),
    !,
    NewTerm = '$builtin'((Term, Din=Dout), [Din, Dout]),
    append(InDegreeVars, [Din, Dout], OutDegreeVars)
  ;
    % quoted term, or existential operator
    (utilities:builtin(Term) ;
     utilities:is_quoted(Functor, '\'') ;
     Functor == '^' ;
     Functor == '$builtin', flags:get_bpl_flag(degree_accumulator(true))),
    !,
    NewTerm = Term,
    OutDegreeVars = InDegreeVars
  ;
    % Defined predicates
    flags:get_bpl_flag(degree_accumulator(false)) 
    ->
      % Non-optimized version: Without degree accumulator
      % Adds the degree variable to the scanned term
      append(Args, [NewDegreeVar], NewArgs),
      prefixed_predicate_name(Functor, NewFunctor),
      NewTerm =.. [NewFunctor|NewArgs],
      % Updates the dynamic degree variable list
      OutDegreeVars = [NewDegreeVar|InDegreeVars]
    ;
      % Optimized version: With degree accumulator
      % Adds the pair of input and output degree variables
      % to the scanned term
      append(Args, [NewDegreeInVar,NewDegreeOutVar], NewArgs),
      prefixed_predicate_name(Functor, NewFunctor),
      NewTerm =.. [NewFunctor|NewArgs],
      % Updates the dynamic degree variable list
      append(InDegreeVars, [NewDegreeInVar, NewDegreeOutVar], OutDegreeVars)
  ),
  !.

degree_variable_scanner(Term, Term, InDegreeVars, InDegreeVars).
  % Term can be ignored because it's a variable or a number

  
%% add_degree_variables_if_total_goal(+Goal, -NewGoal, +Compiled, -GoalDegreeVars)
%
%     Adds degree variables to the goal if it is a total goal.
%     If the goal is a partial goal, it will be passed as is.
%     Compiled is unified with 'yes' if the goal is a total goal
%     and 'no' if it is a partial goal.
%

add_degree_variables_if_total_goal(Goal, NewGoal, Compiled, GoalDegreeVars) :-
  (is_total_goal(Goal)
   ->
    % Call with a known argument
    add_degree_variables(Goal, NewGoal, GoalDegreeVars),
    Compiled = yes
   ;
    % Call with a partial goal as argument
    NewGoal = Goal,
    Compiled = no
  ).


%% ho_prepare_degree_variables(+HOList, +Compiled, +Goal, +GoalDegreeVars, -NewTerm, -InDegreeVars, -OutDegreeVars)
%
%     Encapsulates the Goal for the higher-order predicate call 
%     included in HOList = [HOCall|HOArguments] where Goal is the 
%     argument of the higher-order call HOCALL, which may have other 
%     arguments (for example, in the crisp negation \+ Goal, the list 
%     HOList is [eval_negation, \+]).
%

% Non-optimized version: Without degree accumulator
ho_prepare_degree_variables(HOList, Compiled, Goal, GoalDegreeVars, NewTerm, InDegreeVars, OutDegreeVars) :-
  flags:get_bpl_flag(degree_accumulator(false)),
  !,
  append([ho_call, HOList], [Compiled, Goal, GoalDegreeVars, NewDegreeVar], NewTermList),
  NewTerm =.. NewTermList,
  % Updates the dynamic degree variable list
  append([NewDegreeVar], InDegreeVars, OutDegreeVars).
  
% Optimized version: With degree accumulator
ho_prepare_degree_variables(HOList, Compiled, Goal, GoalDegreeVars, NewTerm, InDegreeVars, OutDegreeVars) :-
  append([ho_call, HOList], [Compiled, Goal, GoalDegreeVars, NewDegreeInVar, NewDegreeOutVar], NewTermList),
  NewTerm =.. NewTermList,
  % Updates the dynamic degree variable list linking the last 
  % variable in InDegreeVars with the first one in the body degree
  % variable list
  append(InDegreeVars, [NewDegreeInVar, NewDegreeOutVar], OutDegreeVars).


%% extract_degree_variables_scanner(+Term, -Term, +InData, -OutData)
%
%     Scanner that can be used with process_term/6 to extract
%     degree variables in OutData from each call to a 
%     user-defined predicate. 
%
%     @see process_term/6
%

extract_degree_variables_scanner(Term, Term, InDegreeVars, OutDegreeVars) :-
    nonvar(Term),
    not(number(Term)),
    !,
    Term =.. [Functor|Args],
    (
      % Term represents a variable, so it can be ignored
      utilities:atom_is_variable(Functor),
      !,
      OutDegreeVars = InDegreeVars
    ;
      % Negation (GoalDegreeVars must not be passed to OutDegreeVars)
      Functor = ho_call,
      Args = [[eval_negation, Neg], yes, _Goal, _GoalDegreeVars|DegreeVars],
      (Neg = not ; Neg = (\+)),
      !,
      append(InDegreeVars, DegreeVars, OutDegreeVars)
    ;
      % Higher order call
      Functor = ho_call,
      Args = [HOList, Compiled, _Goal, GoalDegreeVars|DegreeVars],
      !,
      ( HOList = [HOPredicate|_],
        ho_crisp_predicate(HOPredicate)
        -> OutDegreeVars = InDegreeVars
        ; (Compiled == no
          -> append(InDegreeVars, DegreeVars, OutDegreeVars)
          ;  GoalDegreeVars = [Din|_],
             link_last_variable(GoalDegreeVars, Dout),
             append(InDegreeVars, [Din, Dout], OutDegreeVars)
          )
      )
    ;
      % Hypothetical operator
      flags:get_bpl_flag(hypothetical(true)),
      Term = '=>'(_HypoRules, _Goal),
      !,
      OutDegreeVars = InDegreeVars
    ;
      % Predefined predicate (built-in) withouth degree accumulator
      flags:get_bpl_flag(degree_accumulator(true)),
      flags:get_bpl_flag(disjunction(true)),
      Term = '$builtin'(_Builtin, [Din, Dout]),
      !,
      append(InDegreeVars, [Din, Dout], OutDegreeVars)
    ;
      % Predefined predicate (built-in).
      % quoted term, or existential operator
      ( utilities:builtin(Term) ; 
        utilities:is_quoted(Functor, '\'') ;
        Functor == '^' ),
      !,
      OutDegreeVars = InDegreeVars
    ;
      % Defined predicates
      % Optimized version 
      % Extract the degree variables from the scanned term
      append(_, [DegreeInVar,DegreeOutVar], Args),
      % Add the degree variables to the output data
      append(InDegreeVars, [DegreeInVar, DegreeOutVar], OutDegreeVars)
    ),
    !.
  
  extract_degree_variables_scanner(Term, Term, InDegreeVars, InDegreeVars).
    % Term can be ignored because it's a variable or a number


