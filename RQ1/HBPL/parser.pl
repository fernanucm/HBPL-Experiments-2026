%% add_constraint_variables(+Term, -Result, -ConstraintsVars)
%
%     If the selected weak unification algorithm is either 'a2' or 'a3', 
%     then scans Term, adds an input and output constraint variables
%     to all the calls to non-predefined predicates and returns the 
%     resulting term in Result. ConstraintsVars will be unified
%     with a list containing the constraint variables appended 
%     by this predicate. See
%     constraint_variables_scanner/4 for an example.
%     For other weak unification algorithms, Result is the same Term 
%     and ConstraintsVars is left as is.
%
%     If Term contains a disjunction, all possible paths are examined
%     to link both each input and output constraint variables 
%     of each disjunct. Each disjunct is processed separately and the
%     resulting constraint variables are linked together.
%     The predicate disjunctive_normal_form/2 is used to extract each
%     disjunct.
%
%     @see constraint_variables_scanner/4
%

%% add_constraint_variables_aux(+Term, -Result, -ConstraintsVars)
%
%     Helper predicate for add_constraint_variables/3.

% Weak unification algorithm 'a1'
add_constraint_variables(Term, Term, _ConstraintsVars) :-
  flags:get_bpl_flag(weak_unification('a1')),
  !.

% Weak unification algorithm 'a2' or 'a3'
% Optimized version: With degree accumulator
add_constraint_variables(Term, Result, ConstraintsVars) :-
  flags:get_bpl_flag(disjunction(true)),
  !,
  % Add constraint variables to Term
  add_constraint_variables_aux(Term, NewResult, ConstraintsVars),
  % Extract each disjunct in NewResult
  disjunctive_normal_form(NewResult, DisjTerm),
  utilities:disjunction_to_list(DisjTerm, Disjuncts),
  % Extract the constraint variables in each disjunct
  maplist(extract_constraint_variables, Disjuncts, RestBlockCtrVars),
  % Chain the constraint variables of each disjunct
  maplist(link_accumulator_variables, RestBlockCtrVars),
  utilities:cond_filter_element(utilities:var_or_empty_list, [ConstraintsVars|RestBlockCtrVars], NonEmptyVarsList),
  % Link heads and last element of the degree variables lists
  % For example: [[X1, X2, X3], [Y1, Y2]] -> X1 = Y1, X3 = Y2
  link_heads_and_lasts(NonEmptyVarsList),
  % Recover the original form of built-in predicates, along 
  % with the call Cin = Cout
  replace_builtin(NewResult, Result).
  
% Weak unification algorithm 'a2' or 'a3'
% Non-optimized version: Without degree accumulator
add_constraint_variables(Term, Result, ConstraintsVars) :-
  add_constraint_variables_aux(Term, Result, ConstraintsVars),
  link_accumulator_variables(ConstraintsVars).


add_constraint_variables_aux(Term, Result, ConstraintsVars) :-
  utilities:process_term(Term, Result,
                         [parser:constraint_variables_scanner],
                         [parser:control_predicate_tester],
                         [], ConstraintsVars).



