expression([Exp], [Line, Column]) -->
  operator(Exp, [Line, Column]),
  {
    Exp \== ','
  }.

expression(Exp, [Line, Column]) -->
  term(Exp, [not_allowed_ops([','])], _, [Line, Column]).


